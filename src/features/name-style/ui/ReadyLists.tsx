import { SYMBOLS, readyNames, type Game, type Lang } from "@/features/name-style/domain";
import CopyArea from "@/features/name-style/ui/CopyArea";

const COPY = {
  en: {
    namesH: "Ready-made stylish names to copy", namesP: (n: number) => `${n} names made by this tool from our own word lists, each with its plain spelling. They are not taken from real players. Tap Copy, paste into the game and check that it fits and shows correctly.`,
    symbolsH: "Symbols for names", symbolsP: "Tap a symbol to copy it, then paste it before or after your name. Each is one Unicode character (the last two are short words in small raised letters). Some phones show a symbol their font lacks as an empty box.",
    copy: "Copy", copyPlain: "Copy plain", copyOf: (s: string) => `Copy ${s}`, copyPlainOf: (s: string) => `Copy the plain name ${s}`, symbolOf: (s: string) => `Copy the symbol: ${s}`, plain: "Plain:",
  },
  "pt-BR": {
    namesH: "Nicks prontos com estilo para copiar", namesP: (n: number) => `${n} nicks criados por esta ferramenta a partir das nossas próprias listas de palavras, cada um com a grafia normal. Não são nicks de jogadores reais. Toque em Copiar, cole no jogo e veja se cabe e aparece certo.`,
    symbolsH: "Símbolos para nick", symbolsP: "Toque em um símbolo para copiar e cole antes ou depois do seu nome. Cada um é um caractere Unicode (os dois últimos são palavras curtas em letras pequenas elevadas). Alguns celulares mostram como quadrado o símbolo que a fonte não tem.",
    copy: "Copiar", copyPlain: "Copiar normal", copyOf: (s: string) => `Copiar ${s}`, copyPlainOf: (s: string) => `Copiar o nome normal ${s}`, symbolOf: (s: string) => `Copiar o símbolo: ${s}`, plain: "Normal:",
  },
} as const;

/**
 * The ready-made names and the symbols, as static HTML (the format the top search results use: a long list you tap to copy).
 * Generated by the engine at build time, so the list is the same on every build and never claims to be real players' names.
 */
export default function ReadyLists({ game, lang = "en" }: { game: Game; lang?: Lang }) {
  const c = COPY[lang], names = readyNames(game);
  return (
    <CopyArea game={game} lang={lang}>
      <section aria-labelledby="ready" className="space-y-3">
        <h2 id="ready" className="font-display text-2xl font-bold text-white">{c.namesH}</h2>
        <p className="max-w-3xl leading-7 text-zinc-300">{c.namesP(names.length)}</p>
        <ul className="grid gap-2 sm:grid-cols-2 lg:grid-cols-3" data-testid="ready-names" translate="no">
          {names.map((n) => (
            <li key={n.plain} className="flex items-center gap-2 rounded-lg border border-white/10 bg-surface p-2">
              <span className="min-w-0 flex-1 px-1">
                <span className="block break-all text-lg text-zinc-100">{n.styled}</span>
                <span className="block text-xs text-zinc-400">{c.plain} {n.plain}</span>
              </span>
              <span className="flex flex-col gap-1">
                <button type="button" className="chip" data-copy={n.styled} aria-label={c.copyOf(n.styled)}>{c.copy}</button>
                <button type="button" className="chip text-xs" data-copy={n.plain} aria-label={c.copyPlainOf(n.plain)}>{c.copyPlain}</button>
              </span>
            </li>
          ))}
        </ul>
      </section>
      <section aria-labelledby="symbols" className="space-y-3 pt-8">
        <h2 id="symbols" className="font-display text-2xl font-bold text-white">{c.symbolsH}</h2>
        <p className="max-w-3xl leading-7 text-zinc-300">{c.symbolsP}</p>
        <ul className="flex flex-wrap gap-2" data-testid="symbols" translate="no">
          {SYMBOLS.map((s) => (
            <li key={s.char}><button type="button" className="chip min-w-11 justify-center text-lg" data-copy={s.char} aria-label={c.symbolOf(lang === "en" ? s.en : s.pt)} title={lang === "en" ? s.en : s.pt}>{s.char}</button></li>
          ))}
        </ul>
      </section>
    </CopyArea>
  );
}
