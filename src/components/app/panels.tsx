import type { ComponentType } from "react";

export type Role = "owner" | "editor" | "viewer";
export type PanelGroup = "run" | "share" | "settings";

/** What every panel receives. A panel with controls that change things must check `role` and show a read-only view for "viewer". */
export interface PanelProps { eventId: string; eventName: string; role: Role }

export interface PanelDef {
  id: string;
  group: PanelGroup;
  /** Plain words, shown on the closed disclosure. */
  title: string;
  /** One sentence: what it does for the organiser. */
  blurb: string;
  /** Who sees it. */
  roles: Role[];
  load: () => Promise<{ default: ComponentType<PanelProps> }>;
}

